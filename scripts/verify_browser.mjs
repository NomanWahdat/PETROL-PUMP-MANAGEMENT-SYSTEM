import assert from 'node:assert/strict';
import { writeFileSync, mkdirSync } from 'node:fs';
import { createBrowserClient } from './browser_client.mjs';
const { fixture, call, evaluate, waitFor, navigate, fill, click, login, logout, chooseLanguage, api, addRecord, exceptions, close } = await createBrowserClient();
try {
  await login('platform'); await chooseLanguage('en');
  assert.equal(await evaluate(`Boolean(document.querySelector('a[href="/platform/tenants"]'))`), true);
  await addRecord('/platform/tenants', { name: 'Browser Created Station', slug: 'browser-created-' + fixture.suffix, owner_name: 'Browser Owner', owner_username: 'browser-created-owner-' + fixture.suffix, owner_password: fixture.password }, 'Browser Created Station');
  console.log('PASS: platform login and tenant/initial-owner creation through rendered forms');
  await logout(); await login('owner');
  await addRecord('/products', { name: 'Browser Diesel', code: 'browser-diesel', unit: 'liter', purchase_price: '60.1234', selling_price: '72.5678', minimum_stock: '20' }, 'Browser Diesel');
  const products = (await api('/fuel/products/')).data.results;
  const product = products.find(product => product.code === 'browser-diesel');
  assert.equal(product.selling_price, '72.5678');
  assert.equal((await api('/fuel/price-history/?product=' + product.id)).data.count, 1);
  console.log('PASS: owner product form persists exact decimal prices and initial history');
  await addRecord('/pumps', { name: 'Browser Pump', number: '1', location: 'Front' }, 'Browser Pump');
  const pump = (await api('/pumps/')).data.results[0];
  await addRecord('/tanks', { name: 'Browser Tank', product: product.id, capacity: '1000', opening_quantity: '100', minimum_stock: '20' }, 'Browser Tank');
  const tank = (await api('/tanks/')).data.results[0];
  await addRecord('/nozzles', { number: '1', pump: pump.id, product: product.id, tank: tank.id, opening_meter: '123.456' }, 'Browser Pump');
  assert.equal((await api('/nozzles/')).data.results[0].opening_meter, '123.456');
  console.log('PASS: tank, pump and nozzle setup forms persist valid scoped relationships');
  await addRecord('/employees', { name: 'Browser Attendant', username: 'browser-attendant-' + fixture.suffix, password: fixture.password, role: 'worker', phone: '0700000000' }, 'Browser Attendant');
  await navigate('/station-settings'); await fill('field-name', 'Browser QA Branded Station'); await fill('field-primary_color', '#ffffff');
  await click('.record-form button[type=submit]');
  await waitFor('document.querySelector(".station-brand")?.textContent.includes("Browser QA Branded Station")');
  await waitFor('getComputedStyle(document.documentElement).getPropertyValue("--on-primary").trim() === "#111111"');
  console.log('PASS: employee management and tenant branding/settings through rendered forms');
  await navigate('/products'); await chooseLanguage('fa');
  assert.equal(await evaluate('document.documentElement.dir'), 'rtl');
  assert.equal(await evaluate('document.querySelector("h1")?.textContent'), 'محصولات تیل');
  await chooseLanguage('ps'); assert.equal(await evaluate('document.documentElement.dir'), 'rtl');
  assert.equal(await evaluate('document.querySelector("h1")?.textContent'), 'د تېلو محصولات');
  await chooseLanguage('en'); assert.equal(await evaluate('document.documentElement.dir'), 'ltr');
  mkdirSync('.postgres-test/screenshots', { recursive: true });
  await waitFor('Boolean(document.querySelector("table tbody tr"))');
  writeFileSync('.postgres-test/screenshots/owner.png', Buffer.from((await call('Page.captureScreenshot', { format: 'png' })).data, 'base64'));
  console.log('PASS: English, Dari and Pashto labels and layout direction');
  await logout(); await evaluate('localStorage.removeItem("station-language-explicit")'); await login('worker');
  await waitFor('document.documentElement.dir === "rtl"');
  const links = await evaluate('Array.from(document.querySelectorAll(".sidebar nav a"), a => a.getAttribute("href"))');
  assert.deepEqual(links, ['/', '/account', '/select-station']);
  assert.equal((await api('/fuel/products/')).status, 403);
  await navigate('/employees');
  await waitFor('Boolean(document.querySelector("[role=alert]"))');
  assert.equal(await evaluate('Boolean(document.querySelector(".record-form"))'), false);
  await navigate('/');
  await call('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await waitFor('Boolean(document.querySelector(".nozzle-choices"))');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  writeFileSync('.postgres-test/screenshots/worker-mobile.png', Buffer.from((await call('Page.captureScreenshot', { format: 'png' })).data, 'base64'));
  console.log('PASS: worker has minimal navigation, blocked management routes and mobile RTL layout');
  await logout(); await login('accountant'); await navigate('/products');
  await waitFor('Boolean(document.querySelector("table tbody tr"))');
  assert.equal(await evaluate('Boolean(document.querySelector(".page-heading-actions button"))'), false);
  assert.equal(await evaluate('Boolean(document.querySelector("table button"))'), false);
  assert.deepEqual(exceptions, []);
  console.log('PASS: accountant configuration is read-only; no uncaught browser exceptions');
} finally {
  await close();
}
